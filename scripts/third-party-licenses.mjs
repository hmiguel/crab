#!/usr/bin/env node
// Generates THIRD_PARTY_LICENSES.md: every Rust crate compiled into the app (normal dependencies
// of the `crab` crate for this platform) and every production npm package bundled into the UI,
// with their license texts. Identical texts are printed once. The file ships inside the app bundle.
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const LICENSE_FILE = /^(licen[cs]e|copying|notice)([-._].*)?$/i;

/** @param {{ecosystem: string, name: string, version: string, license: string, texts: string[]}[]} entries */
export function renderNotices(entries) {
  const groups = new Map(); // whitespace-normalised text -> { text, users }
  const missing = [];
  const sorted = [...entries].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  for (const e of sorted) {
    if (e.texts.length === 0) missing.push(e);
    for (const raw of e.texts) {
      const text = raw.replace(/\r\n/g, "\n").trim();
      const key = text.replace(/\s+/g, " ");
      if (!groups.has(key)) groups.set(key, { text, users: [] });
      groups.get(key).users.push(e);
    }
  }
  const line = (e) => `- ${e.name} ${e.version} (${e.ecosystem}, ${e.license || "unknown"})`;
  const out = [
    "# Third-party licenses",
    "",
    "Crab is distributed under MIT OR Apache-2.0. It includes the following third-party software,",
    "listed with the license texts shipped by each package. This file is generated by",
    "`pnpm notices`; do not edit it by hand.",
    "",
  ];
  for (const { text, users } of groups.values()) {
    out.push("---", "", ...users.map(line), "", "```", text, "```", "");
  }
  if (missing.length > 0) {
    out.push("---", "", "No license file was shipped with these packages; their declared license applies:", "", ...missing.map(line), "");
  }
  return out.join("\n");
}

function licenseTexts(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => readFileSync(join(dir, f), "utf8"));
}

function rustEntries(root) {
  const meta = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--filter-platform", hostTarget()], { cwd: root, maxBuffer: 1 << 28 }).toString(),
  );
  const packages = new Map(meta.packages.map((p) => [p.id, p]));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const app = meta.packages.find((p) => p.name === "crab");
  const seen = new Set();
  const queue = [app.id];
  while (queue.length > 0) {
    const id = queue.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const dep of nodes.get(id)?.deps ?? []) {
      if (dep.dep_kinds.some((k) => k.kind === null)) queue.push(dep.pkg);
    }
  }
  return [...seen]
    .map((id) => packages.get(id))
    .filter((p) => p.source) // skip our own workspace crates
    .map((p) => ({ ecosystem: "Rust", name: p.name, version: p.version, license: p.license ?? "", texts: licenseTexts(dirname(p.manifest_path)) }));
}

function hostTarget() {
  const info = execFileSync("rustc", ["-vV"]).toString();
  return info.match(/^host: (.+)$/m)[1].trim();
}

function npmEntries(root) {
  const byLicense = JSON.parse(execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], { cwd: root, maxBuffer: 1 << 26 }).toString());
  return Object.values(byLicense)
    .flat()
    .flatMap((p) =>
      p.versions.map((version, i) => ({ ecosystem: "npm", name: p.name, version, license: p.license, texts: licenseTexts(p.paths[i] ?? p.paths[0]) })),
    );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(fileURLToPath(import.meta.url), "../..");
  const entries = [...rustEntries(root), ...npmEntries(root)];
  writeFileSync(join(root, "THIRD_PARTY_LICENSES.md"), renderNotices(entries));
  console.log(`THIRD_PARTY_LICENSES.md: ${entries.length} packages`);
}
